"""Shared declarations for canonical Tempo benchmark task artifacts."""

from __future__ import annotations

from dataclasses import replace
from pathlib import Path, PurePosixPath

import yaml

from evalkit.api import (
    Copy,
    DockerBuild,
    Environment,
    ImageRef,
    RuntimeDocs,
    RuntimeMaterialization,
    Task,
    copy,
    override,
)
from evalkit.compiler.build import ROOT

CONFIG = yaml.safe_load((ROOT / "config" / "tasks.yaml").read_text())
GENERATED_HEADER = "# AUTO-GENERATED BY npm run sync. DO NOT EDIT MANUALLY."
VERIFIER_INSTRUCTIONS = (
    "RUN mkdir -p /app /logs/agent",
    "COPY . /tests/",
)
ENVIRONMENT_DOCKERFILE = f"{GENERATED_HEADER}\nFROM {CONFIG['images']['agent']}\n"
VERIFIER_DOCKERFILE = (
    f"{GENERATED_HEADER}\nFROM {CONFIG['images']['verifier']}\n"
    + "\n".join(VERIFIER_INSTRUCTIONS)
    + "\n"
)


def _image(role: str) -> ImageRef:
    reference = str(CONFIG["images"][role])
    name, separator, tag = reference.rpartition(":")
    if not separator or not name or not tag:
        raise ValueError(f"Configured {role} image must include a tag: {reference}")
    return ImageRef(name, tag)


def _environment() -> Environment:
    return Environment(
        agent=DockerBuild(_image("agent"), header=GENERATED_HEADER),
        verifier=DockerBuild(
            _image("verifier"),
            header=GENERATED_HEADER,
            instructions=VERIFIER_INSTRUCTIONS,
        ),
    )


def _files(source: Path, destination: str) -> tuple[Copy, ...]:
    root = PurePosixPath(destination)
    return tuple(
        copy(path, root / path.relative_to(source).as_posix())
        for path in sorted(source.rglob("*"))
        if path.is_file()
    )


def _with_generated_assets(
    task: Task,
    *,
    copies: tuple[Copy, ...] = (),
    runtime: RuntimeMaterialization | None = None,
) -> Task:
    destinations = {
        PurePosixPath("environment/Dockerfile"),
        PurePosixPath("tests/Dockerfile"),
        *(item.destination for item in copies),
    }
    existing = {item.destination: item for item in task.overrides}
    for destination in destinations:
        existing[destination] = override(
            destination,
            reason="EvalKit owns canonical generated task assets",
        )
    return replace(
        task,
        copies=(*task.copies, *copies),
        environment=_environment(),
        overrides=tuple(existing[path] for path in sorted(existing)),
        runtime=runtime or RuntimeMaterialization(),
    )


TEMPO_DOCS = RuntimeMaterialization(
    docs=RuntimeDocs(
        input_name="tempo_docs",
        compose_source=ROOT
        / "shared"
        / "tempo"
        / "docker"
        / "compose"
        / "tempo-docs.yaml",
        proxy_source=ROOT / "shared" / "docs" / "static-docs-proxy",
        bundle_destination=PurePosixPath("environment/tempo-docs-bundle"),
        tls_destination=PurePosixPath("environment/docs-tls"),
        hostname="docs.tempo.xyz",
        access_log_source="/var/log/tempo-docs/access.log",
        service="tempo-docs",
    )
)

MPP_DOCS = RuntimeMaterialization(
    docs=RuntimeDocs(
        input_name="mpp_docs",
        compose_source=ROOT / "shared" / "mpp" / "docker" / "compose" / "mpp-docs.yaml",
        proxy_source=ROOT / "shared" / "docs" / "static-docs-proxy",
        bundle_destination=PurePosixPath("environment/mpp-docs-bundle"),
        tls_destination=PurePosixPath("environment/mpp-docs-tls"),
        hostname="mpp.dev",
        access_log_source="/var/log/mpp-docs/access.log",
        service="mpp-docs",
    )
)


def tempo_task(task: Task) -> Task:
    """Compile one Tempo task with canonical environments and runtime docs recipe."""
    return _with_generated_assets(task, runtime=TEMPO_DOCS)


def tempo_mcp_task(task: Task) -> Task:
    """Compile one MCP task with the complete shared MCP harness."""
    shared = ROOT / "shared" / "tempo"
    copies = (
        copy(
            shared / "docker" / "compose" / "tempo-mcp-eval.yaml",
            "environment/docker-compose.yaml",
        ),
        *_files(shared / "mcp-bridge", "environment/mcp-bridge"),
        copy(shared / "mcp-eval" / "check.py", "tests/check.py"),
        copy(shared / "mcp-eval" / "validation.py", "tests/validation.py"),
        copy(shared / "mcp-eval" / "test.sh", "tests/test.sh", mode=0o755),
        copy(task.source / "instruction.md", "tests/instruction.md"),
        *_files(shared / "mcp-eval" / "quality", "tests/quality"),
        copy(shared / "mcp-eval" / "oracle.ts", "solution/oracle.ts"),
        copy(shared / "mcp-eval" / "package.json", "solution/package.json"),
        copy(shared / "mcp-eval" / "tsconfig.json", "solution/tsconfig.json"),
    )
    return _with_generated_assets(task, copies=copies)


def mpp_task(task: Task) -> Task:
    """Compile one MPP task with shared harness assets and runtime docs recipe."""
    task_slug = task.source.name
    local = set(CONFIG["mpp"]["task_local_overrides"].get(task_slug, ()))
    copies = tuple(
        copy(
            ROOT / "shared" / "mpp" / item["path"],
            item["path"],
            mode=0o755 if item.get("executable") else None,
        )
        for item in CONFIG["mpp"]["shared_files"]
        if item["path"] not in local
    )
    return _with_generated_assets(task, copies=copies, runtime=MPP_DOCS)
