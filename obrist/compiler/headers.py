from pathlib import Path

AUTO_GENERATED_TEXT = "AUTO-GENERATED by Obrist. Do not edit directly."

HASH_COMMENT_NAMES = {"Dockerfile", "Makefile"}
HASH_COMMENT_SUFFIXES = {
    ".py",
    ".sh",
    ".bash",
    ".toml",
    ".yaml",
    ".yml",
}
SLASH_COMMENT_SUFFIXES = {".js", ".mjs", ".cjs", ".ts", ".tsx", ".jsonc"}
HTML_COMMENT_SUFFIXES = {".md", ".markdown", ".html"}


def supports_generated_header(path: Path) -> bool:
    """Return whether a generated-file header can be added without breaking syntax."""

    return (
        path.name in HASH_COMMENT_NAMES
        or path.suffix in HASH_COMMENT_SUFFIXES | SLASH_COMMENT_SUFFIXES | HTML_COMMENT_SUFFIXES
    )


def _header(path: Path) -> str:
    if path.suffix in HTML_COMMENT_SUFFIXES:
        return f"<!-- {AUTO_GENERATED_TEXT} -->\n\n"
    if path.suffix in SLASH_COMMENT_SUFFIXES:
        return f"// {AUTO_GENERATED_TEXT}\n"
    return f"# {AUTO_GENERATED_TEXT}\n"


def add_generated_header(path: Path, content: str) -> str:
    """Add an Obrist generated-file header when the file type supports comments."""

    if not supports_generated_header(path):
        return content
    if AUTO_GENERATED_TEXT in content.splitlines()[:3]:
        return content

    header = _header(path)
    if content.startswith("#!"):
        first_line, separator, rest = content.partition("\n")
        if not separator:
            return f"{first_line}\n{header}"
        return f"{first_line}\n{header}{rest}"
    return f"{header}{content}"
