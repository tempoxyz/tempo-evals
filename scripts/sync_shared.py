#!/usr/bin/env python3
"""Generate versioned Tempo tasks and sync shared MPP harness files.

Authored Tempo task templates live in tasks/tempo-v1/_templates/<slug>/. Generated
task directories under tasks/tempo-v1/ contain one un-suffixed and one -mcp
variant per template. Never hand-edit generated tasks; edit the template and re-run
`npm run sync`.
"""

from __future__ import annotations

import json
import shutil
import tomllib
from pathlib import Path
from typing import Any

import tomlkit
import yaml

ROOT = Path(__file__).resolve().parents[1]
TASKS_DIR = ROOT / "tasks" / "tempo-v1"
SOURCES_DIR = TASKS_DIR / "_templates"
SOURCES_LABEL = "tasks/tempo-v1/_templates"
MPP_TASKS_DIR = ROOT / "tasks" / "mpp"
GLOBAL_SHARED_DIR = ROOT / "shared" / "global"
TEMPO_SHARED_DIR = ROOT / "shared" / "tempo"
MPP_SHARED_DIR = ROOT / "shared" / "mpp"

# All task matrix data (task slugs, generated profiles, MPP shared file
# lists, ...) lives in config/tasks.yaml.
TASKS_CONFIG: dict[str, Any] = yaml.safe_load(
    (ROOT / "config" / "tasks.yaml").read_text()
)
BENCHMARKS_CONFIG: dict[str, dict[str, Any]] = yaml.safe_load(
    (ROOT / "config" / "benchmarks.yaml").read_text()
)["benchmarks"]
TEMPO_BENCHMARK = BENCHMARKS_CONFIG["tempo"]
MPP_BENCHMARK = BENCHMARKS_CONFIG["mpp"]
TASK_SLUGS: list[str] = TASKS_CONFIG["task_slugs"]
BASE_IMAGE: str = TASKS_CONFIG["base_image"]
GENERATED_PROFILES: list[dict[str, Any]] = TASKS_CONFIG["profiles"]
ALL_PROFILES: list[dict[str, Any]] = GENERATED_PROFILES
QUALITY_ENV: dict[str, str] = TASKS_CONFIG["quality_env"]
FIXTURE_ENV: dict[str, str] = TASKS_CONFIG["fixture_env"]
CASE_FIXTURES: dict[str, dict[str, str]] = TASKS_CONFIG["case_fixtures"]
EXECUTION_CONSTRAINTS: str = TASKS_CONFIG["execution_constraints"]
MPP_SHARED_FILES: list[dict[str, Any]] = TASKS_CONFIG["mpp"]["shared_files"]
MPP_TASK_LOCAL_OVERRIDES: dict[str, list[str]] = TASKS_CONFIG["mpp"][
    "task_local_overrides"
]

# Replaced with the profile instruction block + execution constraints when
# rendering each source instruction.md into a generated task.
INSTRUCTION_PLACEHOLDER = "<!-- tempobench_sync -->"

# Every task environment builds FROM the shared base image, which bakes in
# the RewardKit venv and the Tempo verifier (shared/global/docker/base/).
TASK_DOCKERFILE = f"""\
# AUTO-GENERATED BY npm run sync. DO NOT EDIT MANUALLY.
# Source: shared/global/docker/base/Dockerfile (pinned as base_image in
# config/tasks.yaml).
FROM {BASE_IMAGE}
"""


def remove_path(target: Path) -> None:
    if target.is_symlink() or target.is_file():
        target.unlink(missing_ok=True)
    elif target.is_dir():
        shutil.rmtree(target)


def skip_node_artifacts(source_path: Path) -> bool:
    parts = source_path.parts
    return "node_modules" in parts or source_path.name == "package-lock.json"


def copy_dir(source: Path, destination: Path) -> None:
    remove_path(destination)
    destination.parent.mkdir(parents=True, exist_ok=True)
    shutil.copytree(
        source,
        destination,
        ignore=lambda directory, names: [
            name for name in names if skip_node_artifacts(Path(directory) / name)
        ],
    )


def copy_file(source: Path, destination: Path) -> None:
    remove_path(destination)
    destination.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(source, destination)


def write_file(destination: Path, content: str) -> None:
    remove_path(destination)
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(content)


def toml_string(value: str) -> str:
    return json.dumps(value)


def toml_array(values: list[str]) -> str:
    return "[ " + ", ".join(toml_string(value) for value in values) + ",]"


def generated_header(source: str) -> str:
    return (
        f"# AUTO-GENERATED BY npm run sync. DO NOT EDIT MANUALLY.\n# Source: {source}\n"
    )


def generated_python_header(source: str) -> str:
    formatted_source = source.replace("/tests/", "/\n#   tests/")
    return (
        "# AUTO-GENERATED BY npm run sync. DO NOT EDIT MANUALLY.\n"
        f"# Source:\n#   {formatted_source}\n"
    )


def render_instruction(task_dir: Path, slug: str, profile: dict[str, Any]) -> None:
    instruction_path = task_dir / "instruction.md"
    content = instruction_path.read_text()
    if content.count(INSTRUCTION_PLACEHOLDER) != 1:
        msg = (
            f"Expected exactly one {INSTRUCTION_PLACEHOLDER} placeholder in "
            f"{SOURCES_LABEL}/{slug}/instruction.md"
        )
        raise RuntimeError(msg)

    parts = []
    if instruction := profile.get("instruction"):
        parts.append(instruction.strip())
    parts.append(EXECUTION_CONSTRAINTS.strip())
    header = (
        f"<!-- AUTO-GENERATED FROM {SOURCES_LABEL}/{slug}/instruction.md "
        "BY npm run sync. DO NOT EDIT MANUALLY. -->\n\n"
    )
    write_file(
        instruction_path,
        header + content.replace(INSTRUCTION_PLACEHOLDER, "\n\n".join(parts)),
    )


def render_readme(task_dir: Path, slug: str) -> None:
    readme_path = task_dir / "README.md"
    if not readme_path.exists():
        msg = f"Missing {SOURCES_LABEL}/{slug}/README.md"
        raise RuntimeError(msg)

    content = readme_path.read_text()
    for heading in ("## Overview", "## What the Task Tests"):
        if heading not in content:
            msg = f"Missing {heading!r} in {SOURCES_LABEL}/{slug}/README.md"
            raise RuntimeError(msg)

    header = (
        f"<!-- AUTO-GENERATED FROM {SOURCES_LABEL}/{slug}/README.md "
        "BY npm run sync. DO NOT EDIT MANUALLY. -->\n\n"
    )
    write_file(readme_path, header + content)


def render_task_env(slug: str, template_env: dict[str, str]) -> dict[str, str]:
    if slug not in CASE_FIXTURES:
        msg = f"Missing case_fixtures entry for {slug!r} in config/tasks.yaml"
        raise RuntimeError(msg)

    merged = dict(FIXTURE_ENV)
    merged.update(CASE_FIXTURES[slug])
    merged.update(template_env)
    return merged


def render_task_toml(task_dir: Path, slug: str, profile: dict[str, Any]) -> None:
    task_config_path = task_dir / "task.toml"
    doc = tomlkit.parse(task_config_path.read_text())

    task = doc["task"]
    task["name"] = f"tempo/{slug}{profile['suffix']}"
    description = str(task.get("description", task["name"]))
    task["description"] = f"{description} ({profile['label']} profile)."
    keywords = task.get("keywords")
    if keywords is not None and profile["id"] not in keywords:
        keywords.append(profile["id"])

    if "metadata" in doc:
        doc["metadata"]["profile"] = profile["id"]
        doc["metadata"]["benchmark"] = TEMPO_BENCHMARK["id"]

    environment = doc["environment"]
    template_env = read_string_table(task_config_path, "environment.env")
    rendered_env = render_task_env(slug, template_env)
    env_table = tomlkit.table()
    for key, value in rendered_env.items():
        env_table[key] = value
    for key, value in profile.get("env", {}).items():
        env_table[key] = value
    for key, value in QUALITY_ENV.items():
        if key not in env_table:
            env_table[key] = value
    environment["env"] = env_table
    if server_configs := profile.get("mcp_servers"):
        servers = tomlkit.aot()
        for server_config in server_configs:
            server = tomlkit.table()
            for key, value in server_config.items():
                server[key] = value
            servers.append(server)
        environment["mcp_servers"] = servers

    header = generated_header(f"{SOURCES_LABEL}/{slug}/task.toml")
    write_file(task_config_path, header + tomlkit.dumps(doc))


def sync_tests(task_dir: Path, slug: str, profile: dict[str, Any]) -> None:
    criteria_path = task_dir / "tests" / "correctness" / "criteria.py"
    if not criteria_path.exists():
        msg = f"Missing {SOURCES_LABEL}/{slug}/tests/correctness/criteria.py"
        raise RuntimeError(msg)
    write_file(
        criteria_path,
        generated_python_header(f"{SOURCES_LABEL}/{slug}/tests/correctness/criteria.py")
        + criteria_path.read_text(),
    )

    write_file(
        task_dir / "tests" / "reward.toml",
        "# AUTO-GENERATED BY npm run sync. DO NOT EDIT MANUALLY.\n"
        '[[reward]]\nname = "reward"\naggregation = "weighted_mean"\n',
    )

    copy_dir(
        GLOBAL_SHARED_DIR / "rewardkit" / "quality", task_dir / "tests" / "quality"
    )
    if check := profile.get("quality_check"):
        check_path = task_dir / "tests" / "quality" / "check.py"
        content = check_path.read_text().rstrip()
        write_file(check_path, f"{content}\n\n{check.rstrip()}\n")

    verify_path = task_dir / "tests" / "correctness" / "verify-tempo.sh"
    copy_file(GLOBAL_SHARED_DIR / "rewardkit" / "verify-tempo.sh", verify_path)
    verify_path.chmod(0o755)

    test_path = task_dir / "tests" / "test.sh"
    copy_file(GLOBAL_SHARED_DIR / "rewardkit" / "test.sh", test_path)
    test_path.chmod(0o755)


def sync_environment(task_dir: Path, _profile: dict[str, Any]) -> None:
    write_file(task_dir / "environment" / "Dockerfile", TASK_DOCKERFILE)


def read_toml(file_path: Path) -> dict[str, Any]:
    return tomllib.loads(file_path.read_text())


def nested_value(data: dict[str, Any], dotted_key: str) -> Any:
    value: Any = data
    for part in dotted_key.split("."):
        if not isinstance(value, dict):
            return None
        value = value.get(part)
    return value


def read_string_table(file_path: Path, table_name: str) -> dict[str, str]:
    table = nested_value(read_toml(file_path), table_name)
    if not isinstance(table, dict):
        return {}
    return {key: value for key, value in table.items() if isinstance(value, str)}


def read_string_value(file_path: Path, dotted_key: str) -> str | None:
    value = nested_value(read_toml(file_path), dotted_key)
    return value if isinstance(value, str) else None


def assert_verifier_env_allowed(task_dir: Path) -> None:
    task_config_path = task_dir / "task.toml"
    verifier_env = read_string_table(task_config_path, "verifier.env")
    environment_mode = read_string_value(task_config_path, "verifier.environment_mode")
    if environment_mode != "separate" and verifier_env:
        msg = (
            "[verifier.env] must be absent unless [verifier].environment_mode = "
            f'"separate" in {task_config_path}'
        )
        raise RuntimeError(msg)


def read_task_case_id(slug: str) -> str | None:
    return CASE_FIXTURES.get(slug, {}).get("TEMPO_BENCH_CASE")


def generate_task(source_dir: Path, slug: str, profile: dict[str, Any]) -> str:
    task_slug = f"{slug}{profile['suffix']}"
    task_dir = TASKS_DIR / task_slug
    copy_dir(source_dir, task_dir)
    render_instruction(task_dir, slug, profile)
    render_readme(task_dir, slug)
    render_task_toml(task_dir, slug, profile)
    assert_verifier_env_allowed(task_dir)

    if not read_task_case_id(slug):
        msg = (
            f"TEMPO_BENCH_CASE is missing for {slug!r} in config/tasks.yaml "
            "case_fixtures"
        )
        raise RuntimeError(msg)

    sync_tests(task_dir, slug, profile)
    sync_environment(task_dir, profile)
    return task_slug


def generate_task_matrix() -> int:
    generated_slugs: set[str] = set()
    for slug in TASK_SLUGS:
        source_dir = SOURCES_DIR / slug
        if not (source_dir / "task.toml").exists():
            msg = f"Missing template task: {source_dir}"
            raise RuntimeError(msg)
        for profile in ALL_PROFILES:
            generated_slugs.add(generate_task(source_dir, slug, profile))

    for entry in TASKS_DIR.iterdir():
        if (
            entry.is_dir()
            and entry.name != "_templates"
            and entry.name not in generated_slugs
        ):
            remove_path(entry)
    return len(generated_slugs)


def read_dataset_digests() -> dict[str, str]:
    return read_manifest_digests(TASKS_DIR / "dataset.toml")


def read_manifest_digests(dataset_path: Path) -> dict[str, str]:
    if not dataset_path.exists():
        return {}

    data = tomllib.loads(dataset_path.read_text())
    return {
        task["name"]: task["digest"]
        for task in data.get("tasks", [])
        if isinstance(task.get("name"), str) and isinstance(task.get("digest"), str)
    }


def matrix_task_names() -> list[str]:
    return [
        f"tempo/{slug}{profile['suffix']}"
        for slug in TASK_SLUGS
        for profile in ALL_PROFILES
    ]


def write_dataset_manifest() -> None:
    digests = read_dataset_digests()
    placeholder_digest = "sha256:" + "0" * 64
    task_entries = "\n".join(
        f"[[tasks]]\nname = {toml_string(name)}\n"
        f"digest = {toml_string(digests.get(name, placeholder_digest))}\n"
        for name in matrix_task_names()
    )
    write_file(
        TASKS_DIR / "dataset.toml",
        f"# Dataset manifest for {TEMPO_BENCHMARK['dataset']}\n"
        "# AUTO-GENERATED BY npm run sync. RUN npm run dataset TO REFRESH DIGESTS.\n\n"
        "[dataset]\n"
        f"name = {toml_string(TEMPO_BENCHMARK['dataset'])}\n"
        f"description = {toml_string(TEMPO_BENCHMARK['description'])}\n"
        f"keywords = {toml_array(TEMPO_BENCHMARK['keywords'])}\n"
        "[[dataset.authors]]\n"
        f"name = {toml_string(TEMPO_BENCHMARK['author'])}\n\n\n"
        f"{task_entries}\n",
    )


def mpp_task_dirs() -> list[Path]:
    if not MPP_TASKS_DIR.exists():
        return []
    return sorted(
        entry
        for entry in MPP_TASKS_DIR.iterdir()
        if entry.is_dir() and (entry / "task.toml").exists()
    )


# Legacy per-task copies now baked into the base image; sync removes them.
MPP_LEGACY_PATHS = [
    "environment/rewardkit-lib",
    "tests/support/client_lib.py",
    "tests/support/oracle_paid_server.ts",
    "tests/support/verifier_utils.py",
]


def sync_mpp_tasks() -> int:
    tasks = mpp_task_dirs()
    for task_dir in tasks:
        overrides = set(MPP_TASK_LOCAL_OVERRIDES.get(task_dir.name, []))
        for shared_file in MPP_SHARED_FILES:
            source = shared_file["path"]
            if source in overrides:
                continue
            destination = task_dir / source
            copy_file(MPP_SHARED_DIR / source, destination)
            if shared_file.get("executable"):
                destination.chmod(0o755)
        write_file(task_dir / "environment" / "Dockerfile", TASK_DOCKERFILE)
        for legacy_path in MPP_LEGACY_PATHS:
            remove_path(task_dir / legacy_path)
        task_config_path = task_dir / "task.toml"
        task_config = tomlkit.parse(task_config_path.read_text())
        task_config["metadata"]["dataset"] = MPP_BENCHMARK["id"]
        task_config["metadata"]["benchmark"] = MPP_BENCHMARK["id"]
        write_file(task_config_path, tomlkit.dumps(task_config))
    return len(tasks)


def write_mpp_dataset_manifest() -> None:
    dataset_path = MPP_TASKS_DIR / "dataset.toml"
    digests = read_manifest_digests(dataset_path)
    placeholder_digest = "sha256:" + "0" * 64
    task_names = [
        read_toml(task_dir / "task.toml")["task"]["name"]
        for task_dir in mpp_task_dirs()
    ]
    task_entries = "\n".join(
        f"[[tasks]]\nname = {toml_string(name)}\n"
        f"digest = {toml_string(digests.get(name, placeholder_digest))}\n"
        for name in task_names
    )
    write_file(
        dataset_path,
        f"# Dataset manifest for {MPP_BENCHMARK['dataset']}\n"
        "# AUTO-GENERATED BY npm run sync. RUN npm run dataset -- --tasks tasks/mpp "
        "TO REFRESH DIGESTS.\n\n"
        "[dataset]\n"
        f"name = {toml_string(MPP_BENCHMARK['dataset'])}\n"
        f"description = {toml_string(MPP_BENCHMARK['description'])}\n"
        f"keywords = {toml_array(MPP_BENCHMARK['keywords'])}\n"
        "[[dataset.authors]]\n"
        f"name = {toml_string(MPP_BENCHMARK['author'])}\n\n\n"
        f"{task_entries}\n",
    )


def main() -> None:
    task_count = generate_task_matrix()
    write_dataset_manifest()
    mpp_task_count = sync_mpp_tasks()
    write_mpp_dataset_manifest()
    print(
        f"Generated {task_count} Tempo task(s) from {SOURCES_LABEL}; "
        f"synced MPP harness into {mpp_task_count} task(s).",
    )


if __name__ == "__main__":
    main()
